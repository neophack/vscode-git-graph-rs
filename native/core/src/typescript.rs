//! The TypeScript type generation behind [`protocol::typescript`](crate::protocol::typescript):
//! the visitor that walks a type's dependencies and collects one declaration per named type, the
//! config the declarations render with, and the output path the `protocol` test writes.
//!
//! The whole module is `ts`-gated (with the derives it serves): the release addon never
//! generates types, so `ts-rs` stays out of its dependency graph entirely.

use std::collections::BTreeMap;
use std::path::PathBuf;

use ts_rs::{Config, TypeVisitor, TS};

// Type declarations are emitted sorted by name, so regeneration is deterministic across rebuilds.
pub(crate) const GENERATED_HEADER: &str = "// @generated by native/core (protocol::typescript) — do not edit.\n// Regenerate with `cargo test -p git-graph-core --test protocol`.\n/* eslint-disable */";

/// Integers are JSON numbers on the wire and `JSON.parse` yields `number`, never `bigint`.
pub(crate) fn config() -> Config {
    Config::new().with_large_int("number")
}

/// Every named type reachable from the protocol's parameters and results, declared once each.
/// The output is keyed by the type's TypeScript name and emitted sorted by it, because the
/// visitor's traversal order is fixed per compilation (see `typescript`).
#[derive(Default)]
pub(crate) struct Declarations {
    seen: Vec<std::any::TypeId>,
    output: BTreeMap<String, String>,
}

impl Declarations {
    pub(crate) fn visit_root<T: TS + 'static + ?Sized>(&mut self, config: &Config) {
        let mut visitor = Visitor {
            config,
            declarations: self,
        };
        visitor.visit::<T>();
    }

    /// The declarations, sorted by their TypeScript names (see the struct's docs).
    pub(crate) fn sorted_output(&self) -> String {
        self.output
            .values()
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join("\n")
    }
}

struct Visitor<'a> {
    config: &'a Config,
    declarations: &'a mut Declarations,
}

impl TypeVisitor for Visitor<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        let named = <T as TS>::output_path().is_some();
        if named {
            let id = std::any::TypeId::of::<T>();
            if self.declarations.seen.contains(&id) {
                return;
            }
            self.declarations.seen.push(id);
        }
        <T as TS>::visit_dependencies(self);
        <T as TS>::visit_generics(self);
        if named {
            let docs = <T as TS>::docs().unwrap_or_default();
            self.declarations.output.insert(
                <T as TS>::name(self.config),
                format!("{docs}export {}", <T as TS>::decl(self.config)),
            );
        }
    }
}

/// Where `cargo test` writes the generated module, relative to the repository root. `pub`
/// because `protocol` re-exports it as `typescript_output_path` for the `protocol` test.
pub fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/shared/engine/protocol.ts")
}
