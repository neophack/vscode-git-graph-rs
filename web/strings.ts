/**
 * The currently active string dictionary (module-global, read by all web sources).
 */
let strings: WebviewStrings = STRINGS_EN;

/**
 * Get the string dictionary for an interface language.
 * @param lang The language code ('en' or 'zh-cn'; anything else falls back to English).
 */
function getStrings(lang: string): WebviewStrings {
	return lang === 'zh-cn' ? STRINGS_ZH_CN : STRINGS_EN;
}

/**
 * Switch the active string dictionary (called during webview start-up).
 * @param lang The language code ('en' or 'zh-cn').
 */
function setInterfaceLanguage(lang: string) {
	strings = getStrings(lang);
}

/**
 * Substitute {0}, {1}, ... placeholders in a string from the active dictionary.
 * @param template The template string.
 * @param args The values to substitute.
 */
function formatStr(template: string, ...args: string[]): string {
	return template.replace(/\{(\d+)\}/g, (match, index) => typeof args[index] === 'string' ? args[index] : match);
}
